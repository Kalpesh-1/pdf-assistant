"""Section 3: Understand Document.

Offers a fixed set of guided questions about the document. Each one is a
preset instruction sent to the language model along with document content, so
the user does not have to think of a question to get oriented.

Each option's answer is cached separately in session state, so re-selecting an
option that has already been run costs nothing. The cache is cleared with the
document.
"""

from __future__ import annotations

from dataclasses import dataclass

import streamlit as st

from pdf_assistant.config import Settings
from pdf_assistant.models.schemas import ProcessingStatus
from pdf_assistant.services.summary_service import explain_document
from pdf_assistant.ui import state
from pdf_assistant.ui.errors import GENERATION_ERRORS


@dataclass(frozen=True)
class UnderstandOption:
    """One guided-explanation option.

    Attributes:
        key: Stable identifier, used as the Streamlit widget key.
        label: Button text shown to the user.
        description: One line explaining what the option produces.
        instruction: The task description sent to the language model.
    """

    key: str
    label: str
    description: str
    instruction: str


# All eight options required by the specification. Keeping them as data rather
# than eight separate functions means Phase 3 only needs one handler.
UNDERSTAND_OPTIONS: tuple[UnderstandOption, ...] = (
    UnderstandOption(
        key="about",
        label="What is this document about?",
        description="A plain-English description of the document's subject.",
        instruction=(
            "Describe what this document is about in simple English, in 4 to 6 sentences."
        ),
    ),
    UnderstandOption(
        key="purpose",
        label="What is its purpose?",
        description="Why the document was written and who it is for.",
        instruction=(
            "Explain the purpose of this document and who its intended readers are. "
            "Use simple English."
        ),
    ),
    UnderstandOption(
        key="topics",
        label="Main topics",
        description="The major subjects the document covers.",
        instruction=(
            "List the main topics covered in this document as short bullet points, "
            "in the order they appear."
        ),
    ),
    UnderstandOption(
        key="sections",
        label="Important sections",
        description="The key sections and what each one contains.",
        instruction=(
            "Identify the important sections of this document. For each one, give its "
            "name and one sentence explaining what it contains."
        ),
    ),
    UnderstandOption(
        key="key_points",
        label="Key points",
        description="The most important facts and statements.",
        instruction=(
            "List the most important key points from this document as bullet points. "
            "Keep each point to one sentence."
        ),
    ),
    UnderstandOption(
        key="terms",
        label="Difficult terms explained",
        description="Technical words defined in everyday language.",
        instruction=(
            "Find the difficult or technical terms used in this document and explain each "
            "one in simple English that a beginner could understand."
        ),
    ),
    UnderstandOption(
        key="conclusions",
        label="Main conclusions",
        description="What the document concludes or recommends.",
        instruction=(
            "Identify the main conclusions or recommendations stated in this document. "
            "If the document does not state any conclusions, say so."
        ),
    ),
    UnderstandOption(
        key="presentation",
        label="How to present this document",
        description="A short speaking guide for explaining it to someone else.",
        instruction=(
            "Explain how to present this document to another person. Suggest the order "
            "to cover the material and the points worth emphasising."
        ),
    ),
)


def render(settings: Settings) -> None:
    """Draw the Understand Document section."""
    st.header("Understand Document")

    if not state.has_document():
        st.info(
            "**No PDF uploaded yet.** Upload a document in the sidebar to use these "
            "guided explanations."
        )
        return

    if not settings.has_api_key:
        st.error(
            "**Groq API key missing.** These explanations are generated by the AI model, "
            "so a key is required. Copy `.env.example` to `.env` and add your key."
        )
        return

    st.caption(
        "Pick an option below. Each one reads your document and explains it in simple "
        "English. Long documents are processed in pieces rather than in a single large "
        "request, so they stay within the model's limits."
    )

    # Two columns of buttons, which fits all eight options without scrolling.
    columns = st.columns(2)
    for index, option in enumerate(UNDERSTAND_OPTIONS):
        with columns[index % 2]:
            if st.button(
                option.label,
                key=f"understand_{option.key}",
                help=option.description,
                use_container_width=True,
                disabled=not state.is_ready(),
            ):
                # Button was clicked - generate and show this option
                _generate_and_show_explanation(settings, option)

    if not state.is_ready():
        st.divider()
        if state.get_status() == ProcessingStatus.FAILED:
            st.info(
                "These options stay disabled because this document could not be "
                "processed. See the Document Details section for the reason."
            )
        else:
            st.info(
                "These options become active once this document has finished processing. "
                f"Current status: **{state.get_status().value}**."
            )
        return

    # Show the most recently selected explanation, if any
    _render_current_explanation()


def _generate_and_show_explanation(settings: Settings, option: UnderstandOption) -> None:
    """Generate (if needed) and mark an explanation for display.

    This is called when the user clicks one of the eight option buttons. If the
    explanation is already cached, we just mark it as the current one. Otherwise
    we call explain_document, cache the result, and mark it as current.

    Each option's try/except is independent, so one failing option leaves the
    other seven usable.

    Args:
        settings: Configuration including the API key and model name.
        option: The option the user clicked.
    """
    # Check cache first - if this option was already run, just mark it as current
    cached = state.get_explanation(option.key)
    if cached:
        state.set_current_explanation_key(option.key)
        return

    chunks = state.get_chunks()

    try:
        with st.spinner(f"Generating '{option.label}'..."):
            explanation = explain_document(settings, chunks, option.instruction)
            state.set_explanation(option.key, explanation)
            state.set_current_explanation_key(option.key)
    except GENERATION_ERRORS as exc:
        # Show the error but don't cache it or mark it as current, so the user can retry
        st.error(f"Could not generate '{option.label}': {exc}")


def _render_current_explanation() -> None:
    """Show the currently selected explanation, if any.

    Renders the explanation marked as current (the last one the user clicked)
    under the button grid with the option's label as a heading.
    """
    current_key = state.get_current_explanation_key()
    if not current_key:
        return

    # Find the option and get its explanation
    current_option = None
    for option in UNDERSTAND_OPTIONS:
        if option.key == current_key:
            current_option = option
            break

    if not current_option:
        return

    explanation = state.get_explanation(current_key)
    if explanation:
        st.divider()
        st.markdown(f"### {current_option.label}")
        st.markdown(explanation)
